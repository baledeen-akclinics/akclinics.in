<h2 class="bg-primary">Causes of Pigmentation of Pigmentation</h2>
<p>Since there different types of body and facial pigmentation, the causes can also vary, but some of the main causes include:</p>
	
	
	<ul class="content-list">
<li>Excessive exposure to the sun – this can lead to an increase in the production of melanin</li>
<li>If there has been an inflammation in the skin due to some reason, that could cause hyperpigmentation </li>
<li>Some types of medicines, especially the ones used for chemotherapy can cause hyperpigmentation </li>
	<li>Conditions such as pregnancy can cause a hormonal change in the body and that can increase melanin production</li>
		<li>Medical conditions such as Addison’s disease can affect the body’s adrenal glands and that can alter the melanin production of the body </li>
	</ul>
	

<h2 class="bg-primary">Types of Pigmentation</h2>
<p>There are mainly four types of pigmentation </p>
<ul class="content-list">
        <li><strong>Freckles –</strong> Perhaps the most common type of hyperpigmentation, this presents in the form of clusters of tiny spots that appear generally on the face and in some cases on the back. </li>
		<li><strong>Melasma –</strong> This type of pigmentation manifests deeper in the skin and tends to appear on the face in the form of dark patches. The condition can become worse due to over exposure to the sun, pregnancy or certain medical conditions. </li>
<li><strong>Sunspots –</strong> Also known as liver spots or solar lentigines, these are spots that have more defined edges and can vary in colour. These are the spots that can develop into more serious conditions, such as skin cancer or melanoma. </li>
	<li><strong>Post-inflammatory –</strong> Pigmentation that arises due to acne, abrasion or even certain chemical based treatments is referred to as post inflammatory. </li>
</ul>	
	
