<h2 class="bg-primary">Common Symptoms of Pigmentation</h2>
<p>So how do you find out if you have pigmentation; you need to look at the most common symptoms, as this is something that you could check on your own. Some of the most common symptoms would include: </p>
	<ul class="content-list">

		<li>You notice areas on the skin that look darker than the rest of the skin and this could be on any part of the body</li>
		<li>There are patches of skin that were normal but start looking darker over a short span</li>
		<li>Tiny spots that arise in clusters on the face or body, such as freckles on the face </li>
