<h2 class="bg-primary">What is Pigmentation/Hyperpigmentation?</h2>
<p>Our body produces a pigment called melanin and when there is too much melanin production in the body, it can lead to spots appearing on your skin. This condition is known as hyperpigmentation and there are a few main types – melasma, sunspots and post-inflammatory. Each is caused by a slightly different reason and could lead to different problems if left untreated.</p> 

	

 
