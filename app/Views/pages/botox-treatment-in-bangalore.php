<p>Botox is a shortened form of botulinum toxin and this is a neurotoxic protein that is commonly used in the field of medicine. When this protein is introduced into the body, it is able to inhibit the release of neurotransmitters, which causes a temporary paralysis. These injections are most commonly used to treat fine lines and wrinkles. 

	

 
