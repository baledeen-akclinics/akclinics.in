	<h1 class="main-heading blue-color">FUT Hair Transplant in Bangalore</h1></div>

<p>Commonly known as strip surgery, Follicular Unit Transplant or FUT hair transplant surgery is one of the most popular methods of hair transplant. This is the commonly chosen procedure for situations where the recipient area is large and a greater number of grafts are required. A strip of hair will be taken from the donor area and the area will carefully sutured back, leaving nothing more than a thin scar, which should get covered easily when the hair grows back. The extracted strip of hair is divided into grafts, each of which will consist one or two hair follicles. These grafts are then implanted into the donor area, in a manner that is not much different from <a href="/fue-hair-transplant-in-bangalore/" class="orange-link">FUE</a>. </p>
	
<h2 class="bg-primary">How FUT hair transplant works?</h2>
<p>The process of a <a href="/fut-hair-transplant-in-bangalore/" class="orange-link">FUT hair transplant</a> starts from the time of your first consultation where the donor and recipient areas are identified. This is what normally follows:</p>
<ul class="content-list">
<li>On the day of the procedure, the new hairline will be marked with a marker.</li>
<li>The strip of hair will be removed from the donor area and stored with care.</li>
<li>The part of the scalp where the strip was removed will be stitched back.</li>
<li>Grafts will be removed from the strip of hair and kept in a medical solution till the time they are ready for implantation. </li>
	<li>The grafts will be implanted into the recipient area. </li>
	<li>In some clinics, <a href="/prp-treatment-for-hair-in-bangalore/" class="orange-link">PRP after hair transplant</a> is provided, because that is shown to provide much better results.</li>
</ul></br>
	<p>You will also be given a set of instructions about how to take care of your newly implanted grafts and it is imperative that you adhere to all of them. </p>

	

 
