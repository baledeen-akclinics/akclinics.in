	<ul class="content-list">
<li><strong>Age –</strong> this is perhaps the biggest factor, because if you are too young, the hair loss might not have stabilised</li>
		<li><strong>Type of hair loss –</strong> the conditions that are leading to the <a href="/hair-loss-treatment-in-bangalore/" class="orange-link">hair loss</a> will have a role to play in whether a transplant will work</li>
		<li><strong>Hair type –</strong> some types of hair are better suited for transplant than others</li>
		
</ul>


	<h2 class="bg-primary">How much does FUT Hair Transplant cost?</h2>
<p>FUT hair transplant cost is not something that is fixed, because it is based on a range of factors. These factors could vary from the geographical location of the clinic to the clientele; however the main ones include:</p>
	
	<ul class="content-list">
        <li>The expertise of the surgeon who is doing the actual procedure – the more experienced and practised the hand, the higher the charge</li>
		<li>The licenses, accreditation, certifications of the clinic and practising doctors – the higher the levels of accreditation and licensing, the costing could be on the higher side </li>
		<li>The extent of the donor and recipient areas – if the donor area is very large and the recipient area small, it could mean that extraction needs to be done from other parts of the body</li>
		<li>The number of grafts extracted and utilised – the number of grafts used and the time taken to extract them will play a role. FUT cost per graft is one of the most important factors that decide the final costing. </li>
	</ul>
	
	
<h2 class="bg-primary">Recovery time after FUT Hair Transplant</h2>
<p>While you should be able to return home the same day, you will need to rest for the first few days, post which you should be able to resume most of your normal activities. </p>
<ul class="content-list">
        <li>Your first hair wash will be after 48 hours and you will be asked not to stand under a shower or use hot water. </li>
		<li>You will also be asked to sleep with your head slightly elevated. </li>
		<li>No matter how much it itches, you cannot itch, as that could lead to the grafts falling out. </li>
