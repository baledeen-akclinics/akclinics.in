<h2 class="bg-primary">Types of Hair Loss</h2>
<p>For the common man, hair loss is just that losing hair, but there are several different typesof hair loss and in order to treat them, understating the type is imperative and that is something that a hair fall doctor in Bangalore could tell you. Here are some of the most common types of hair losses:</p>
	<ul class="content-list">

		<li><strong>Androgenic alopecia</strong> – Perhaps one of the most common causes of hair loss, this is a condition that can affect both men and women and is not necessarily age specific. This is also known as male or female pattern baldness and leads to a receding hairline and then a gradual appearance of baldness, mainly from the front of the temple and centre of crown. In women, it would probably present itself as an overall thinning all over the head and the bald patches are very rare. </li>
		<li><strong>Alopecia areata</strong> – This is a condition that is most commonly seen in children and adults of a younger age group – in this condition, there could be complete baldness or hair falling out in patches. In the most severe conditions, there could be loss of hair from other parts of the body too, including eyebrows. However, this condition is normally not permanent and in most people, the hair returns in a matter of months or years. </li>
		<li><strong>Alopecia universalis</strong> – As the name suggests, this is a condition in which affects the entire body – a person who is affected by this condition will lose hair from all parts of their body, including their head, eyebrows, eyelashes, arms, legs and even the pubic region. This is the most severe form of alopecia areata and can affect anyone, irrespective of age. Studies have shown that this is an autoimmune condition and while it can continue lifelong, there is a chance that it resolves on its own. </li>
		<li><strong>Trichotillomania</strong> – This is the type of hair loss that you see most commonly in small children, when they constantly pull at their hair. This is a condition that can be seen in adults too, caused by stress – when people pull their hair or run their fingers through their hair all the time. There are some people who tend to chew on their hair and all these can lead to hair loss. </li>
		<li><strong>Traction alopecia</strong> – Yet again this is the type of hair loss that is caused by people – when you tie your hair really tight, you are putting unnecessary tension on the roots of the hair; this leads to the hair breaking and eventually hair loss. Whether you are trying your hair in cornrows or really tight buns or ponytails, these types of hair styles are leading to stress on the hair. This type of hair loss can be avoided by tying your hair in soft or gentle hair styles.   </li>
		<li><strong>Scarring alopecia</strong> – This is one of the conditions that can lead to permanent hair loss and it can be caused due to several reasons including inflammatory skin conditions such as acne, cellulitis and folliculitis. Certain skin disorders like lupus and lichen planus can also cause this type of hair loss. These skin conditions can hamper the ability of hair to regenerate, leading to hair loss and hair is unable to regrow. </li>
	</ul>
